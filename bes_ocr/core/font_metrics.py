# Типовой межстрочный шаг Times New Roman при одинарном интервале Word
# (ascent 0.891 + descent 0.216 em), в долях кегля.
SINGLE_LINE_PITCH_EM = 1.107


def glyph(char: str) -> Optional[tuple[int, int, int, int]]:
    return _GLYPHS.get(char)


def vertical_extent_em(text: str) -> Optional[tuple[float, float]]:
    """(верх, низ) чернил слова относительно базовой линии в em, или None,
    если в слове нет ни одного известного глифа."""
    top = None
    bottom = None
    for ch in text:
        g = _GLYPHS.get(ch)
        if g is None:
            continue
        top = g[0] if top is None else max(top, g[0])
        bottom = g[1] if bottom is None else max(bottom, g[1])
    if top is None:
        return None
    return top / 1000.0, bottom / 1000.0


def _significant(text: str) -> int:
    return sum(1 for ch in text if ch.isalnum())


def size_from_height(text: str, height_pt: float) -> Optional[float]:
    """Кегль по высоте рамки слова с учётом того, какие глифы в нём есть."""
    if _significant(text) == 0 or height_pt <= 0:
        return None
    ext = vertical_extent_em(text)
    if ext is None:
        return None
    span = ext[0] + ext[1]
    if span < 0.3:
        return None
    return height_pt / span


def advance_em(text: str, bold: bool = False) -> Optional[float]:
    """Суммарная ширина глифов слова (без межсловных пробелов) в em, или
    None, если в слове есть неизвестные глифы (оценка по ширине тогда
    ненадёжна)."""
    total = 0
    idx = 3 if bold else 2
    for ch in text:
        g = _GLYPHS.get(ch)
        if g is None:
            return None
        total += g[idx]
    return total / 1000.0


def ink_width_em(text: str, bold: bool = False) -> Optional[float]:
    """Ширина "чернил" слова (без боковых полей крайних глифов) в em."""
    adv = advance_em(text, bold)
    if not adv or not text:
        return None
    first, last = _GLYPHS[text[0]], _GLYPHS[text[-1]]
    lsb = first[6] if bold else first[4]
    rsb = last[7] if bold else last[5]
    return max(adv - (lsb + rsb) / 1000.0, adv * 0.5)


def size_from_width(text: str, width_pt: float, bold: bool = False) -> Optional[float]:
    """Кегль по ширине рамки слова. Надёжна только для достаточно длинных
    слов: у коротких заметную долю ширины составляют боковые поля глифов."""
    if _significant(text) < 4 or width_pt <= 0:
        return None
    ink = ink_width_em(text, bold)
    if not ink:
        return None
    return width_pt / ink
