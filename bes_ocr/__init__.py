"""BES OCR — локальный конвертер PDF в редактируемый DOCX."""
import os

# Tesseract использует OpenMP для внутренней многопоточности одного вызова.
# Конвейер (pipeline.py) обрабатывает несколько страниц ПАРАЛЛЕЛЬНО через
# ThreadPoolExecutor, и каждая страница может запускать свой процесс
# tesseract (напрямую через pytesseract и через img2table). Без этого
# ограничения каждый такой процесс пытается забрать под OpenMP все ядра
# машины — при нескольких одновременных страницах получается многократная
# перезапись/переподписка на одни и те же ядра (N воркеров × M
# OpenMP-потоков каждый), и вместо ожидаемых секунд обработка одной
# страницы растягивается на много МИНУТ (проверено: конкурентный OCR двух
# страниц реального документа — тайм-аут >90 c без этой настройки против
# ~12 c с ней). Ставим здесь, на уровне импорта пакета, чтобы это
# гарантированно применялось раньше первого вызова Tesseract, независимо от
# точки входа (GUI, тесты, прямой запуск pipeline).
os.environ.setdefault("OMP_THREAD_LIMIT", "1")

__version__ = "0.1.0"
__app_name__ = "BES OCR"
